/** Quality display keys used across list/detail pages. */
export function qualityNameKey(n: number): string {
  return `LC_COMMON_quality_name_${n}`
}

export function forceCardQualityNameKey(n: number): string {
  const keys: Record<number, string> = {
    2: 'LC_Dynamis_Green',
    3: 'LC_Dynamis_Blue',
    4: 'LC_Dynamis_Purple',
    5: 'LC_Dynamis_Orange',
    6: 'LC_Dynamis_Red',
  }
  return keys[n] ?? `LC_Dynamis_Green`
}

/** Standard hero quality filter values. */
export const HERO_QUALITY_IDS = [2, 3, 4, 5] as const

function flattenObject(obj: Record<string, string>): string[] {
  return Object.values(obj)
}

/** All static LC keys from UI_KEYS for preload/audit. */
export const ALL_UI_LC_KEYS: string[] = [
  ...flattenObject(UI_KEYS.common),
  ...flattenObject(UI_KEYS.nav),
  ...flattenObject(UI_KEYS.filter),
  ...flattenObject(UI_KEYS.list),
  ...flattenObject(UI_KEYS.hero),
  ...flattenObject(UI_KEYS.artifact),
  ...flattenObject(UI_KEYS.companion),
  ...flattenObject(UI_KEYS.item),
  ...flattenObject(UI_KEYS.forceCard),
  ...flattenObject(UI_KEYS.teamBuilder),
  ...HERO_QUALITY_IDS.map(qualityNameKey),
  ...([2, 3, 4, 5, 6] as const).map(forceCardQualityNameKey),
]
